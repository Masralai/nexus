#!/usr/bin/env bun
/**
 * Generates the typed SDK request surface from the shared route contract.
 *
 * Paths stay in `src/server/contract.ts`; this script only reads them, so the
 * SDK can never drift from what the server serves. Run `bun run sdk:generate`
 * after changing the route table or the response map, or with `--check` to
 * verify the committed file is current.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { ROUTES, type RouteDefinition, type RouteName } from "../src/server/contract"

const OUTPUT = fileURLToPath(new URL("../src/sdk/generated.ts", import.meta.url))
const HEADER = [
  "// Generated by `bun run sdk:generate` from src/server/contract.ts. Do not edit.",
  "// Regenerate after changing the route table or the response map.",
].join("\n")

function paramKeys(path: string): string[] {
  return [...path.matchAll(/:([A-Za-z0-9_]+)/g)].map((match) => match[1]!)
}

function paramType(path: string): string {
  const parts = paramKeys(path).map((key) => `${key}: string`)
  if (path.endsWith("*")) parts.push('"*": string')
  return parts.length > 0 ? `{ ${parts.join("; ")} }` : "{}"
}

/** Routes served as event or socket streams get no JSON request method. */
function hasRequestMethod(name: RouteName): boolean {
  const wire = (ROUTES[name] as RouteDefinition).wire
  return wire !== "sse" && wire !== "socket"
}

export function renderSdk(): string {
  const names = Object.keys(ROUTES) as RouteName[]
  const params = names.map((name) => `  ${name}: ${paramType(ROUTES[name].path)}`)
  const methods = names.filter(hasRequestMethod).map((name) => {
    if (paramType(ROUTES[name].path) === "{}") {
      return `    ${name}: (init?: RouteInit) => request("${name}", {}, init),`
    }
    return `    ${name}: (params: RouteParams["${name}"], init?: RouteInit) => request("${name}", params, init),`
  })
  return [
    HEADER,
    "",
    'import type { ResponseOf, RouteInit, RouteName } from "../server/contract"',
    "",
    "/** Path parameters for every route, parsed from its path pattern. */",
    "export interface RouteParams {",
    ...params,
    "}",
    "",
    "export type RouteRequest = <N extends RouteName>(",
    "  name: N,",
    "  params: RouteParams[N],",
    "  init?: RouteInit,",
    ") => Promise<ResponseOf<N>>",
    "",
    "/** One typed method per JSON route in the contract. */",
    "export function createRouteSurface(request: RouteRequest) {",
    "  return {",
    ...methods,
    "  }",
    "}",
    "",
  ].join("\n")
}

if (import.meta.main) {
  const next = renderSdk()
  if (process.argv.includes("--check")) {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : ""
    if (current !== next) {
      console.error("src/sdk/generated.ts is stale — run `bun run sdk:generate`")
      process.exit(1)
    }
    console.log("src/sdk/generated.ts is up to date")
  } else {
    writeFileSync(OUTPUT, next)
    console.log("wrote src/sdk/generated.ts")
  }
}
